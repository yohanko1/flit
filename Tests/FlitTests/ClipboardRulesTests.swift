import Testing
import Foundation
@testable import Flit

struct ClipboardPolicyTests {
    let plain = ["public.utf8-plain-text", "public.rtf"]

    @Test func ordinaryCopiesAreRecorded() {
        #expect(ClipboardPolicy.shouldRecord(types: plain, sourceApp: "com.apple.Safari", ignoreConcealed: true, ignoredApps: []))
        #expect(ClipboardPolicy.shouldRecord(types: plain, sourceApp: nil, ignoreConcealed: true, ignoredApps: ["com.other"]))
    }

    @Test func passwordManagerSecretsAreSkippedUnlessTheUserOptsIn() {
        let secret = plain + ["org.nspasteboard.ConcealedType"]
        #expect(!ClipboardPolicy.shouldRecord(types: secret, sourceApp: nil, ignoreConcealed: true, ignoredApps: []))
        #expect(ClipboardPolicy.shouldRecord(types: secret, sourceApp: nil, ignoreConcealed: false, ignoredApps: []))
    }

    @Test func transientAndGeneratedContentIsNeverRecorded() {
        for marker in ["org.nspasteboard.TransientType", "org.nspasteboard.AutoGeneratedType"] {
            #expect(!ClipboardPolicy.shouldRecord(types: plain + [marker], sourceApp: nil, ignoreConcealed: false, ignoredApps: []))
        }
    }

    @Test func copiesMadeInAnIgnoredAppAreSkipped() {
        #expect(!ClipboardPolicy.shouldRecord(types: plain, sourceApp: "com.example.vault", ignoreConcealed: true, ignoredApps: ["com.example.vault"]))
    }
}

struct ClipboardRowsTests {
    private func store() throws -> (ClipboardStore, URL) {
        let dir = FileManager.default.temporaryDirectory.appendingPathComponent("flit-test-\(UUID().uuidString)")
        let s = try ClipboardStore(directory: dir)
        s.add(.text("meeting notes", rtf: nil, html: nil), app: nil, now: Date(timeIntervalSince1970: 1))
        s.add(.text("home address draft", rtf: nil, html: nil), app: nil, now: Date(timeIntervalSince1970: 2))
        s.addSnippet(name: "address", text: "1 Infinite Loop")
        s.addSnippet(name: "sig", text: "Best regards")
        return (s, dir)
    }

    private func labels(_ rows: [ClipRow]) -> [String] {
        rows.map {
            switch $0 {
            case .snippet(let s): return "snippet:\(s.name)"
            case .entry(let e): return "entry:\(e.text)"
            }
        }
    }

    @Test func withNoQueryHistoryShowsOnlyCopiesNewestFirst() throws {
        let (s, dir) = try store(); defer { try? FileManager.default.removeItem(at: dir) }
        #expect(labels(ClipRow.build(store: s, mode: .history, query: "")) == ["entry:home address draft", "entry:meeting notes"])
    }

    @Test func searchingHistoryListsMatchingSnippetsAheadOfMatchingCopies() throws {
        let (s, dir) = try store(); defer { try? FileManager.default.removeItem(at: dir) }
        #expect(labels(ClipRow.build(store: s, mode: .history, query: "address")) == ["snippet:address", "entry:home address draft"])
    }

    @Test func snippetsModeListsOnlySnippetsAndFiltersThem() throws {
        let (s, dir) = try store(); defer { try? FileManager.default.removeItem(at: dir) }
        #expect(labels(ClipRow.build(store: s, mode: .snippets, query: "")) == ["snippet:address", "snippet:sig"])
        #expect(labels(ClipRow.build(store: s, mode: .snippets, query: "regards")) == ["snippet:sig"])
    }

    @Test func rowsOfDifferentKindsNeverShareAnIdentity() throws {
        let (s, dir) = try store(); defer { try? FileManager.default.removeItem(at: dir) }
        let ids = ClipRow.build(store: s, mode: .history, query: "a").map(\.id)
        #expect(Set(ids).count == ids.count)
    }
}

struct PollScheduleTests {
    @Test func rightAfterInputACopyIsNoticedWithinHalfASecond() throws {
        let delay = try #require(PollSchedule.next(quietFor: 0, hasInputSignal: true))
        #expect(delay <= 0.5)
    }

    @Test func checksThinOutAsTheKeyboardAndMouseStayQuiet() throws {
        let soon = try #require(PollSchedule.next(quietFor: 0.5, hasInputSignal: true))
        let later = try #require(PollSchedule.next(quietFor: 3, hasInputSignal: true))
        #expect(later > soon)
    }

    @Test func afterAQuietSpellPollingStopsUntilTheNextInput() {
        #expect(PollSchedule.next(quietFor: 10, hasInputSignal: true) == nil)
        #expect(PollSchedule.next(quietFor: 86_400, hasInputSignal: true) == nil)
    }

    @Test func withoutAnInputSignalPollingSlowsDownButNeverStops() throws {
        // No Accessibility grant, or a password field holding the keyboard: flit can't see key presses.
        let active = try #require(PollSchedule.next(quietFor: 0, hasInputSignal: false))
        #expect(active <= 0.5)
        let idle = try #require(PollSchedule.next(quietFor: 86_400, hasInputSignal: false))
        #expect(idle > active)
        #expect(idle <= 5)
    }
}
